import { useEffect, useState } from 'react';
import { getMyPayroll } from '../../services/api';
import PageHeader from '../../components/PageHeader';
import LoadingSpinner from '../../components/LoadingSpinner';
import { formatDate } from '../../utils/helpers';
import toast from 'react-hot-toast';
import { CheckCircle, Clock, IndianRupee, TrendingUp, TrendingDown } from 'lucide-react';

function fmt(n) { return `₹${(n ?? 0).toLocaleString('en-IN')}`; }

function monthLabel(ym) {
  if (!ym) return '';
  const [y, m] = ym.split('-');
  return new Date(+y, +m - 1, 1).toLocaleString('en-IN', { month: 'long', year: 'numeric' });
}

export default function MySalary() {
  const [records, setRecords] = useState([]);
  const [loading, setLoading] = useState(true);
  const [expanded, setExpanded] = useState(null); // _id of open card

  useEffect(() => {
    getMyPayroll()
      .then(res => setRecords(res.data))
      .catch(() => toast.error('Failed to load salary records'))
      .finally(() => setLoading(false));
  }, []);

  return (
    <div className="p-4 lg:p-8">
      <PageHeader title="My Salary" subtitle="Monthly salary breakdown" />

      {loading ? <LoadingSpinner /> : records.length === 0 ? (
        <div className="card text-center py-16 text-gray-400">
          <IndianRupee className="w-10 h-10 mx-auto mb-3 opacity-20" />
          <p className="font-medium">No salary records yet</p>
          <p className="text-sm mt-1">Your payroll will appear here once it's generated by admin.</p>
        </div>
      ) : (
        <div className="space-y-3">
          {records.map(r => {
            const isOpen  = expanded === r._id;
            const bonus   = (r.adjustments || []).filter(a => a.type === 'bonus').reduce((s, a) => s + a.amount, 0);
            const extraDed = (r.adjustments || []).filter(a => a.type === 'deduction').reduce((s, a) => s + a.amount, 0);

            return (
              <div key={r._id} className="card hover:shadow-md transition-shadow">
                {/* Header row — always visible */}
                <button
                  className="w-full text-left"
                  onClick={() => setExpanded(isOpen ? null : r._id)}
                >
                  <div className="flex items-center justify-between gap-3">
                    <div>
                      <p className="font-semibold text-gray-900">{monthLabel(r.month)}</p>
                      <p className="text-xs text-gray-400 mt-0.5">
                        {r.workingDays} working days · {r.presentDays} present
                      </p>
                    </div>
                    <div className="text-right flex-shrink-0">
                      <p className="text-lg font-bold text-gray-900">{fmt(r.netSalary)}</p>
                      {r.status === 'paid' ? (
                        <span className="badge-green flex items-center gap-1 justify-end text-xs">
                          <CheckCircle className="w-3 h-3" /> Paid
                        </span>
                      ) : r.status === 'on_hold' ? (
                        <span className="badge-yellow flex items-center gap-1 justify-end text-xs">
                          <Clock className="w-3 h-3" /> On Hold
                        </span>
                      ) : (
                        // 'not_released' or legacy 'pending'
                        <span className="badge-gray flex items-center gap-1 justify-end text-xs">
                          <Clock className="w-3 h-3" /> Not Released
                        </span>
                      )}
                    </div>
                  </div>
                </button>

                {/* Expanded breakdown */}
                {isOpen && (
                  <div className="mt-4 pt-4 border-t border-gray-100 space-y-3 text-sm">
                    {/* Attendance pills */}
                    <div className="grid grid-cols-2 sm:grid-cols-4 gap-2">
                      {[
                        { l: 'Working Days', v: r.workingDays,  c: 'bg-blue-50 text-blue-700'   },
                        { l: 'Present',      v: r.presentDays,  c: 'bg-green-50 text-green-700' },
                        { l: 'Absent',       v: r.absentDays,   c: r.absentDays  > 0 ? 'bg-amber-50 text-amber-700' : 'bg-gray-50 text-gray-400' },
                        { l: 'On Leave',     v: r.leaveDays,    c: r.leaveDays   > 0 ? 'bg-red-50 text-red-600'    : 'bg-gray-50 text-gray-400' },
                      ].map(x => (
                        <div key={x.l} className={`rounded-xl p-3 text-center ${x.c}`}>
                          <p className="text-base font-bold leading-none">{x.v}</p>
                          <p className="text-xs mt-0.5">{x.l}</p>
                        </div>
                      ))}
                    </div>

                    {/* Salary breakdown */}
                    <div className="space-y-1.5 text-sm">
                      <div className="flex justify-between text-gray-600">
                        <span>Monthly Salary</span>
                        <span className="font-medium text-gray-900">{fmt(r.monthlySalary)}</span>
                      </div>
                      <div className="flex justify-between text-gray-500 text-xs">
                        <span>Per Day Rate ({r.workingDays} working days)</span>
                        <span>{fmt(r.perDaySalary)}/day</span>
                      </div>
                      {r.absentDays > 0 && (
                        <div className="flex justify-between text-amber-600">
                          <span className="flex items-center gap-1"><TrendingDown className="w-3.5 h-3.5" /> Absent ({r.absentDays}d × {fmt(r.perDaySalary)})</span>
                          <span className="font-medium">− {fmt(parseFloat((r.absentDays * r.perDaySalary).toFixed(2)))}</span>
                        </div>
                      )}
                      {r.leaveDays > 0 && (
                        <div className="flex justify-between text-red-500">
                          <span className="flex items-center gap-1"><TrendingDown className="w-3.5 h-3.5" /> Leave ({r.leaveDays}d × {fmt(r.perDaySalary)})</span>
                          <span className="font-medium">− {fmt(parseFloat((r.leaveDays * r.perDaySalary).toFixed(2)))}</span>
                        </div>
                      )}
                      {r.totalDeduction > 0 && (
                        <div className="flex justify-between text-gray-500 text-xs border-t border-gray-100 pt-1">
                          <span>Total deduction ({r.deductedDays} days)</span>
                          <span className="font-medium text-red-500">− {fmt(r.totalDeduction)}</span>
                        </div>
                      )}
                      {bonus > 0 && (
                        <div className="flex justify-between text-green-600">
                          <span className="flex items-center gap-1"><TrendingUp className="w-3.5 h-3.5" /> Bonus</span>
                          <span className="font-medium">+ {fmt(bonus)}</span>
                        </div>
                      )}
                      {extraDed > 0 && (
                        <div className="flex justify-between text-red-500">
                          <span className="flex items-center gap-1"><TrendingDown className="w-3.5 h-3.5" /> Extra Deduction</span>
                          <span className="font-medium">− {fmt(extraDed)}</span>
                        </div>
                      )}
                      <div className="flex justify-between border-t border-gray-100 pt-2 font-bold text-gray-900">
                        <span>Net Salary</span>
                        <span>{fmt(r.netSalary)}</span>
                      </div>
                    </div>

                    {/* Adjustment reasons */}
                    {(r.adjustments || []).length > 0 && (
                      <div className="space-y-1">
                        <p className="text-xs font-semibold text-gray-400 uppercase tracking-wider">Adjustments</p>
                        {r.adjustments.map((a, i) => (
                          <div key={i} className={`flex items-center justify-between text-xs px-3 py-1.5 rounded-lg ${
                            a.type === 'bonus' ? 'bg-green-50 text-green-700' : 'bg-red-50 text-red-600'
                          }`}>
                            <span>{a.type === 'bonus' ? '+ Bonus' : '− Deduction'}: {a.reason}</span>
                            <span className="font-semibold">{fmt(a.amount)}</span>
                          </div>
                        ))}
                      </div>
                    )}

                    {/* Paid info */}
                    {r.status === 'paid' && r.paidOn && (
                      <p className="text-xs text-gray-400">
                        Paid on {formatDate(r.paidOn)}{r.paidBy?.name ? ` by ${r.paidBy.name}` : ''}
                      </p>
                    )}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
